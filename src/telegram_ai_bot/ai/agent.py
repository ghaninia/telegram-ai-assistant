"""Turns chat history + knowledge into a Gemini request and returns the reply text."""

import logging
from collections.abc import Callable, Sequence
from datetime import datetime

from telegram_ai_bot import config
from telegram_ai_bot.ai.errors import FALLBACK_WORTHY, AIError, AIErrorKind
from telegram_ai_bot.ai.gemini import GeminiClient
from telegram_ai_bot.core.calendar import describe_now
from telegram_ai_bot.core.models import ChatMessage, KnowledgeItem
from telegram_ai_bot.storage.settings import AppSettings

log = logging.getLogger(__name__)

MEDIA_PLACEHOLDER = "[media or file without text]"


def build_system_prompt(base: str, knowledge: Sequence[KnowledgeItem], now: datetime | None = None) -> str:
    prompt = f"{base.rstrip()}\n\nCurrent date and time: {describe_now(now)}"
    if knowledge:
        facts = "\n\n".join(f"## {k.title}\n{k.content}" for k in knowledge)
        prompt += f"\n\n# Knowledge\n\n{facts}"
    return prompt


def build_contents(messages: Sequence[ChatMessage], limit: int = config.HISTORY_LIMIT) -> list[dict]:
    """Map chat history to Gemini 'contents', merging consecutive messages from the same side."""
    contents: list[dict] = []
    for msg in messages[-limit:]:
        role = "user" if msg.is_incoming else "model"
        text = msg.text.strip() or MEDIA_PLACEHOLDER
        if contents and contents[-1]["role"] == role:
            contents[-1]["parts"][0]["text"] += "\n" + text
        else:
            contents.append({"role": role, "parts": [{"text": text}]})
    # Gemini requires the conversation to start with a user turn.
    while contents and contents[0]["role"] != "user":
        contents.pop(0)
    return contents


class ReplyAgent:
    def __init__(self, settings: AppSettings, knowledge: Sequence[KnowledgeItem],
                 client_factory: Callable[..., GeminiClient] = GeminiClient):
        self._settings = settings
        self._knowledge = knowledge
        self._client = client_factory(api_key=settings.api_key, base_url=settings.base_url, proxy=settings.proxy)

    def reply(self, messages: Sequence[ChatMessage]) -> str | None:
        """Reply to the conversation, or None if the last message is ours (nothing to answer)."""
        contents = build_contents(messages)
        if not contents or contents[-1]["role"] != "user":
            return None
        system = build_system_prompt(self._settings.system_prompt, self._knowledge)

        last_error: AIError | None = None
        for model in self._settings.models:
            try:
                text = self._client.generate(model, system, contents)
                log.info("reply generated by %s (%d chars)", model, len(text))
                return text
            except AIError as e:
                log.warning("model %s failed: %s", model, e)
                last_error = e
                if e.kind not in FALLBACK_WORTHY:
                    break
        raise last_error or AIError(AIErrorKind.UNKNOWN, "no models configured")
